#!/usr/bin/env node
// @cysys/themes generator.
//
// Vendors shadcn "registry:style" theme items (e.g. from tweakcn.com) into
// registry/<name>.json and compiles them into scoped CSS so any number of
// themes can coexist on one page and be switched at runtime with
// `data-theme="<name>"` (plus the usual `.dark` class for dark mode).
//
//   node scripts/themes.mjs add <url|file> [--name x] [--title "X"] [--default] [--no-install]
//   node scripts/themes.mjs sync [name...]   re-fetch themes from their source URLs
//   node scripts/themes.mjs build            regenerate css/ and src/index.ts
//   node scripts/themes.mjs check            fail if generated files are stale
//   node scripts/themes.mjs list
//   node scripts/themes.mjs default <name>   set the fallback theme
//   node scripts/themes.mjs remove <name>

import { execFileSync } from "node:child_process"
import { existsSync } from "node:fs"
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const MANIFEST = join(ROOT, "themes.json")
const REGISTRY_DIR = join(ROOT, "registry")
const CSS_DIR = join(ROOT, "css")
const INDEX_TS = join(ROOT, "src", "index.ts")
const PKG_JSON = join(ROOT, "package.json")

const HEADER =
  "/* AUTO-GENERATED by packages/themes/scripts/themes.mjs — do not edit.\n" +
  " * Edit registry/*.json or themes.json and run `pnpm themes:build`. */"

// Fonts that ship with operating systems (or are CSS generics) and therefore
// need no webfont package.
const SYSTEM_FONTS = new Set(
  [
    "serif", "sans-serif", "monospace", "cursive", "fantasy", "system-ui",
    "ui-serif", "ui-sans-serif", "ui-monospace", "ui-rounded", "math",
    "emoji", "-apple-system", "blinkmacsystemfont", "segoe ui", "roboto",
    "helvetica", "helvetica neue", "arial", "georgia", "times",
    "times new roman", "cambria", "garamond", "palatino", "verdana",
    "tahoma", "trebuchet ms", "courier", "courier new", "menlo", "monaco",
    "consolas", "sf mono", "sfmono-regular", "liberation mono",
    "apple color emoji", "segoe ui emoji", "noto color emoji",
  ].map((f) => f.toLowerCase())
)

const SWATCH_KEYS = ["background", "foreground", "primary", "secondary", "accent", "muted", "border"]

// ---------------------------------------------------------------------------
// helpers

const readJson = async (p) => JSON.parse(await readFile(p, "utf8"))
const writeJson = (p, v) => writeFile(p, JSON.stringify(v, null, 2) + "\n")

function slugify(s) {
  return String(s)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
}

function titleize(slug) {
  return slug
    .split("-")
    .map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w))
    .join(" ")
}

async function loadManifest() {
  if (!existsSync(MANIFEST)) return { default: null, themes: [] }
  return readJson(MANIFEST)
}

async function fetchItem(source) {
  let text
  if (/^https?:\/\//.test(source)) {
    const res = await fetch(source, { headers: { accept: "application/json" } })
    if (!res.ok) throw new Error(`GET ${source} -> ${res.status} ${res.statusText}`)
    text = await res.text()
  } else {
    text = await readFile(resolve(process.cwd(), source), "utf8")
  }
  const item = JSON.parse(text)
  if (!item?.cssVars?.light || !item?.cssVars?.dark) {
    throw new Error(`${source} is not a shadcn theme (missing cssVars.light/dark)`)
  }
  return item
}

function firstFamily(value) {
  if (!value) return null
  const first = String(value).split(",")[0].trim().replace(/^['"]|['"]$/g, "")
  return first || null
}

function themeFonts(item) {
  const vars = { ...item.cssVars.theme, ...item.cssVars.light }
  const out = {}
  for (const role of ["sans", "serif", "mono"]) {
    const fam = firstFamily(vars[`font-${role}`])
    if (fam) out[role] = fam
  }
  return out
}

function npmExists(pkg) {
  try {
    return execFileSync("npm", ["view", pkg, "version"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim()
  } catch {
    return null
  }
}

// Map a font family name to a Fontsource package (variable build preferred).
// Returns { pkg, version, imports[] } or null for system / unknown fonts.
function resolveFontPackage(family) {
  if (SYSTEM_FONTS.has(family.toLowerCase())) return null
  const slug = slugify(family)
  const variable = `@fontsource-variable/${slug}`
  let version = npmExists(variable)
  if (version) return { family, pkg: variable, version, imports: [variable] }
  const stat = `@fontsource/${slug}`
  version = npmExists(stat)
  if (version) {
    return { family, pkg: stat, version, imports: [400, 500, 600, 700].map((w) => `${stat}/${w}.css`) }
  }
  console.warn(`  ! no Fontsource package found for "${family}" — load it yourself`)
  return null
}

// ---------------------------------------------------------------------------
// CSS generation

function selectors(name, isDefault) {
  const scope = `[data-theme="${name}"]`
  // `:root${scope}` out-ranks the neutral `:root {}` baseline in
  // @cysys/ui/globals.css regardless of stylesheet order; the bare scope
  // lets a theme be applied to any subtree.
  const light = [`:root${scope}`, scope]
  const dark = [`:root${scope}.dark`, `${scope}.dark`, `.dark ${scope}`]
  if (isDefault) {
    // Fallback when no data-theme attribute is present anywhere.
    light.unshift(":root:not([data-theme])")
    dark.unshift(":root.dark:not([data-theme])")
  }
  return { scope, light, dark }
}

function declBlock(sel, vars, indent = "") {
  const lines = Object.entries(vars).map(([k, v]) => `${indent}  --${k}: ${v};`)
  return `${indent}${sel.join(`,\n${indent}`)} {\n${lines.join("\n")}\n${indent}}`
}

// Serialize the registry item's optional `css` object. Rules targeting
// html/body/:root are re-targeted at the theme scope so they only apply
// where the theme is active (inheritable props like letter-spacing still
// cascade to descendants).
function serializeCss(obj, scopeSel, indent = "") {
  const out = []
  for (const [key, val] of Object.entries(obj)) {
    if (typeof val !== "object" || val === null) {
      out.push(`${indent}${key}: ${val};`)
      continue
    }
    const isAtRule = key.startsWith("@")
    const isDecls = Object.values(val).every((v) => typeof v !== "object")
    let sel = key
    if (!isAtRule && isDecls) {
      sel = key
        .split(",")
        .map((s) => s.trim())
        .flatMap((s) =>
          /^(html|body|:root)$/.test(s)
            ? scopeSel
            : scopeSel.map((sc) => `${sc} ${s}`)
        )
        .join(", ")
    }
    out.push(`${indent}${sel} {\n${serializeCss(val, scopeSel, indent + "  ")}\n${indent}}`)
  }
  return out.join("\n")
}

function renderThemeCss(entry, item, isDefault) {
  const { light, dark } = selectors(entry.name, isDefault)
  const parts = [HEADER, `/* ${entry.title} — ${entry.source} */`]
  const imports = (entry.fonts ?? []).flatMap((f) => f.imports)
  if (imports.length) parts.push([...new Set(imports)].map((i) => `@import "${i}";`).join("\n"))
  parts.push(declBlock(light, { ...item.cssVars.theme, ...item.cssVars.light }))
  parts.push(declBlock(dark, item.cssVars.dark))
  if (item.css && Object.keys(item.css).length) {
    parts.push(serializeCss(item.css, light))
  }
  return parts.join("\n\n") + "\n"
}

function renderAllCss(manifest) {
  const lines = manifest.themes.map((t) => `@import "./${t.name}.css";`)
  return [HEADER, lines.join("\n")].join("\n\n") + "\n"
}

function renderIndexTs(manifest, items) {
  const data = manifest.themes.map((t) => {
    const item = items[t.name]
    const pick = (mode) =>
      Object.fromEntries(SWATCH_KEYS.filter((k) => item.cssVars[mode][k]).map((k) => [k, item.cssVars[mode][k]]))
    return {
      name: t.name,
      title: t.title,
      source: t.source,
      fonts: themeFonts(item),
      radius: item.cssVars.theme?.radius ?? item.cssVars.light.radius ?? null,
      swatches: { light: pick("light"), dark: pick("dark") },
    }
  })
  return `// AUTO-GENERATED by packages/themes/scripts/themes.mjs — do not edit.
// Run \`pnpm themes:build\` after changing registry/*.json or themes.json.

export type ThemeMode = "light" | "dark"

export interface CysysTheme {
  /** Value for the \`data-theme\` attribute. */
  name: string
  title: string
  /** Where the theme was imported from (tweakcn / shadcn registry URL). */
  source: string
  fonts: { sans?: string; serif?: string; mono?: string }
  radius: string | null
  /** A few representative colors, handy for theme pickers. */
  swatches: Record<ThemeMode, Record<string, string>>
}

export const themes = ${JSON.stringify(data, null, 2)} as const satisfies readonly CysysTheme[]

export type ThemeName = (typeof themes)[number]["name"]

/** Applied via \`:root:not([data-theme])\` when no theme is selected. */
export const defaultTheme = ${JSON.stringify(manifest.default)} as ThemeName${manifest.default ? "" : " | null"}

export const themeNames: readonly ThemeName[] = themes.map((t) => t.name)

export function isThemeName(value: unknown): value is ThemeName {
  return typeof value === "string" && (themeNames as readonly string[]).includes(value)
}

export function getTheme(name: ThemeName): CysysTheme {
  return themes.find((t) => t.name === name)!
}
`
}

async function generate(manifest) {
  const items = {}
  for (const t of manifest.themes) items[t.name] = await readJson(join(REGISTRY_DIR, `${t.name}.json`))
  const files = new Map()
  for (const t of manifest.themes) {
    files.set(join(CSS_DIR, `${t.name}.css`), renderThemeCss(t, items[t.name], t.name === manifest.default))
  }
  files.set(join(CSS_DIR, "all.css"), renderAllCss(manifest))
  files.set(INDEX_TS, renderIndexTs(manifest, items))
  return files
}

async function build(manifest) {
  manifest ??= await loadManifest()
  const files = await generate(manifest)
  await mkdir(CSS_DIR, { recursive: true })
  // Drop CSS for themes that no longer exist.
  for (const f of await readdir(CSS_DIR)) {
    if (f.endsWith(".css") && !files.has(join(CSS_DIR, f))) await rm(join(CSS_DIR, f))
  }
  for (const [p, content] of files) await writeFile(p, content)
  console.log(`Built ${manifest.themes.length} theme(s): ${manifest.themes.map((t) => t.name).join(", ")}`)
}

async function check() {
  const manifest = await loadManifest()
  const files = await generate(manifest)
  const stale = []
  for (const [p, content] of files) {
    const current = existsSync(p) ? await readFile(p, "utf8") : null
    if (current !== content) stale.push(p.replace(ROOT + "/", ""))
  }
  if (stale.length) {
    console.error(`Generated theme files are stale: ${stale.join(", ")}\nRun \`pnpm themes:build\`.`)
    process.exit(1)
  }
  console.log("Theme files are up to date.")
}

async function syncFontDeps(manifest) {
  const pkg = await readJson(PKG_JSON)
  const deps = { ...(pkg.dependencies ?? {}) }
  const wanted = new Map()
  for (const t of manifest.themes) for (const f of t.fonts ?? []) wanted.set(f.pkg, f.version)
  let changed = false
  for (const [name, version] of wanted) {
    if (!deps[name]) {
      deps[name] = `^${version}`
      changed = true
    }
  }
  for (const name of Object.keys(deps)) {
    if (name.startsWith("@fontsource") && !wanted.has(name)) {
      delete deps[name]
      changed = true
    }
  }
  if (changed) {
    pkg.dependencies = Object.fromEntries(Object.entries(deps).sort(([a], [b]) => a.localeCompare(b)))
    await writeJson(PKG_JSON, pkg)
  }
  return changed
}

async function importTheme(manifest, source, opts = {}) {
  const item = await fetchItem(source)
  const name = slugify(opts.name ?? item.name ?? "")
  if (!name) throw new Error("Theme has no name; pass --name")
  const existing = manifest.themes.find((t) => t.name === name)
  const title = opts.title ?? existing?.title ?? titleize(name)
  const finalSource = /^https?:\/\//.test(source) ? source : existing?.source ?? source

  console.log(`• ${name}: resolving fonts…`)
  const fonts = Object.values(themeFonts(item))
    .filter((v, i, a) => a.indexOf(v) === i)
    .map(resolveFontPackage)
    .filter(Boolean)

  await mkdir(REGISTRY_DIR, { recursive: true })
  await writeJson(join(REGISTRY_DIR, `${name}.json`), item)

  const entry = { name, title, source: finalSource, fonts }
  if (existing) Object.assign(existing, entry)
  else manifest.themes.push(entry)
  if (opts.default || !manifest.default) manifest.default = name
  return entry
}

function install() {
  console.log("Installing font packages…")
  execFileSync("pnpm", ["install"], { cwd: ROOT, stdio: "inherit" })
}

// ---------------------------------------------------------------------------
// CLI

function parseArgs(argv) {
  const positional = []
  const flags = {}
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (a === "--") continue
    if (a.startsWith("--")) {
      const key = a.slice(2)
      const next = argv[i + 1]
      if (next !== undefined && !next.startsWith("--") && ["name", "title"].includes(key)) {
        flags[key] = next
        i++
      } else flags[key] = true
    } else positional.push(a)
  }
  return { positional, flags }
}

async function main() {
  const [cmd, ...rest] = process.argv.slice(2)
  const { positional, flags } = parseArgs(rest)
  const manifest = await loadManifest()

  switch (cmd) {
    case "add": {
      if (!positional.length) throw new Error("usage: add <url|file> [--name x] [--title X] [--default]")
      if (positional.length > 1 && (flags.name || flags.title)) throw new Error("--name/--title only work with a single source")
      for (const src of positional) {
        const e = await importTheme(manifest, src, flags)
        console.log(`  added ${e.name} (${e.title})`)
      }
      await writeJson(MANIFEST, manifest)
      const depsChanged = await syncFontDeps(manifest)
      await build(manifest)
      if (depsChanged && !flags["no-install"]) install()
      break
    }
    case "sync": {
      const targets = positional.length ? positional : manifest.themes.map((t) => t.name)
      for (const name of targets) {
        const t = manifest.themes.find((x) => x.name === name)
        if (!t) throw new Error(`Unknown theme ${name}`)
        if (!/^https?:\/\//.test(t.source)) {
          console.log(`• ${name}: local source, skipping`)
          continue
        }
        await importTheme(manifest, t.source, { name: t.name })
      }
      await writeJson(MANIFEST, manifest)
      const depsChanged = await syncFontDeps(manifest)
      await build(manifest)
      if (depsChanged && !flags["no-install"]) install()
      break
    }
    case "remove": {
      for (const name of positional) {
        manifest.themes = manifest.themes.filter((t) => t.name !== name)
        await rm(join(REGISTRY_DIR, `${name}.json`), { force: true })
        if (manifest.default === name) manifest.default = manifest.themes[0]?.name ?? null
      }
      await writeJson(MANIFEST, manifest)
      await syncFontDeps(manifest)
      await build(manifest)
      break
    }
    case "default": {
      const [name] = positional
      if (!manifest.themes.some((t) => t.name === name)) throw new Error(`Unknown theme ${name}`)
      manifest.default = name
      await writeJson(MANIFEST, manifest)
      await build(manifest)
      break
    }
    case "build":
      await build(manifest)
      break
    case "check":
      await check()
      break
    case "list":
      for (const t of manifest.themes) {
        console.log(`${t.name === manifest.default ? "*" : " "} ${t.name.padEnd(24)} ${t.title.padEnd(24)} ${t.source}`)
      }
      break
    default:
      console.log(
        "usage: themes.mjs <add|sync|build|check|list|default|remove> …\n" +
          "  add <url|file>… [--name x] [--title X] [--default] [--no-install]"
      )
      process.exit(cmd ? 1 : 0)
  }
}

main().catch((err) => {
  console.error(err.message ?? err)
  process.exit(1)
})
